package writer

import (
	"cmp"
	"slices"
	"strconv"
	"strings"

	"github.com/bidirekt/go-sdk/internal/model"
)

const (
	header               = "# Generated by github.com/bidirekt/go-sdk. Do not edit."
	indentStep           = "  "
	maxImplicitKeyLength = 1024
)

type yamlMap struct {
	pairs []yamlPair
}

type yamlPair struct {
	key   yamlKey
	value yamlValue
}

type yamlKey interface {
	keyToText(childIndent string) (text string, explicit bool)
}

type nameKey string

type statusKey int

type yamlValue interface {
	yamlValue()
}

type scalar string

type flowSequence []string

type trueValue struct{}

type nullValue struct{}

func (*yamlMap) yamlValue()     {}
func (scalar) yamlValue()       {}
func (flowSequence) yamlValue() {}
func (trueValue) yamlValue()    {}
func (nullValue) yamlValue()    {}

func (this *yamlMap) add(key yamlKey, value yamlValue) {
	this.pairs = append(this.pairs, yamlPair{key: key, value: value})
}

func ContractToYaml(contract model.Contract) string {
	root := &yamlMap{}
	if len(contract.Provides) > 0 {
		root.add(nameKey("provides"), providedToYaml(contract.Provides))
	}
	if len(contract.Consumes) > 0 {
		root.add(nameKey("consumes"), consumedToYaml(contract.Consumes))
	}
	if len(contract.Schemas) > 0 {
		root.add(nameKey("schemas"), schemasToYaml(contract.Schemas))
	}
	return header + "\n" + mapToText(root, "") + "\n"
}

func providedToYaml(resources []model.Resource) *yamlMap {
	rest := &yamlMap{}
	rest.add(nameKey("rest"), resourcesToYaml(resources))
	return rest
}

func consumedToYaml(resources []model.Resource) *yamlMap {
	providers := &yamlMap{}
	for _, group := range resourcesToSortedGroups(resources, func(resource model.Resource) string { return resource.Provider }) {
		providers.add(nameKey(group[0].Provider), providedToYaml(group))
	}
	return providers
}

func resourcesToSortedGroups(resources []model.Resource, resourceToKey func(model.Resource) string) [][]model.Resource {
	groups := model.ResourcesToGroups(resources, resourceToKey)
	slices.SortFunc(groups, func(a, b []model.Resource) int { return strings.Compare(resourceToKey(a[0]), resourceToKey(b[0])) })
	return groups
}

func resourcesToYaml(resources []model.Resource) *yamlMap {
	endpoints := &yamlMap{}
	for _, group := range resourcesToSortedGroups(resources, func(resource model.Resource) string { return resource.Path }) {
		atPath := slices.SortedStableFunc(slices.Values(group), func(a, b model.Resource) int {
			return strings.Compare(strings.ToLower(a.Method), strings.ToLower(b.Method))
		})
		methods := &yamlMap{}
		for _, resource := range atPath {
			methods.add(nameKey(strings.ToLower(resource.Method)), resourceToYaml(resource))
		}
		endpoints.add(nameKey(group[0].Path), methods)
	}
	return endpoints
}

func resourceToYaml(resource model.Resource) *yamlMap {
	interaction := &yamlMap{}
	if resource.Request != nil {
		interaction.add(nameKey("request"), bodyToYaml(*resource.Request))
	}
	byStatus := slices.SortedStableFunc(slices.Values(resource.Responses), func(a, b model.Response) int {
		return cmp.Compare(a.Status, b.Status)
	})
	responses := &yamlMap{}
	for _, response := range byStatus {
		responses.add(statusKey(response.Status), bodyToYaml(response.Body))
	}
	interaction.add(nameKey("responses"), responses)
	return interaction
}

func bodyToYaml(body model.Body) yamlValue {
	if body.Schema == "" {
		return nullValue{}
	}
	return scalar(body.Schema)
}

func schemasToYaml(schemas []model.NamedSchema) *yamlMap {
	sorted := slices.SortedStableFunc(slices.Values(schemas), func(a, b model.NamedSchema) int {
		return strings.Compare(a.Name, b.Name)
	})
	named := &yamlMap{}
	for _, schema := range sorted {
		named.add(nameKey(schema.Name), nodeToYaml(schema.Node))
	}
	return named
}

func nodeToYaml(node model.Node) *yamlMap {
	fields := &yamlMap{}
	switch shape := node.Shape.(type) {
	case model.Ref:
		fields.add(nameKey("ref"), scalar(shape.Schema))
	case model.Object:
		fields.add(nameKey("type"), scalar("object"))
		properties := &yamlMap{}
		for _, property := range shape.Properties {
			properties.add(nameKey(property.Name), nodeToYaml(property.Node))
		}
		fields.add(nameKey("properties"), properties)
	case model.Array:
		fields.add(nameKey("type"), scalar("array"))
		fields.add(nameKey("items"), nodeToYaml(shape.Items))
	case model.Map:
		fields.add(nameKey("type"), scalar("map"))
		fields.add(nameKey("values"), nodeToYaml(shape.Values))
	case model.Enum:
		fields.add(nameKey("type"), scalar("enum"))
		fields.add(nameKey("members"), flowSequence(shape.Members))
	case model.Union:
		fields.add(nameKey("type"), scalar("union"))
		members := &yamlMap{}
		for _, member := range shape.Members {
			members.add(nameKey(member.Key), nodeToYaml(member.Node))
		}
		fields.add(nameKey("members"), members)
	case model.Primitive:
		fields.add(nameKey("type"), scalar(shape.Type))
	}
	if node.Optional {
		fields.add(nameKey("optional"), trueValue{})
	}
	if node.Nullable {
		fields.add(nameKey("nullable"), trueValue{})
	}
	if node.Description != "" {
		fields.add(nameKey("description"), scalar(node.Description))
	}
	return fields
}

// indent is the indentation of the map's own lines.
func mapToText(yaml *yamlMap, indent string) string {
	if len(yaml.pairs) == 0 {
		return "{}"
	}
	lines := make([]string, 0, len(yaml.pairs))
	for _, pair := range yaml.pairs {
		lines = append(lines, pairToText(pair, indent))
	}
	return strings.Join(lines, "\n"+indent)
}

func pairToText(pair yamlPair, indent string) string {
	childIndent := indent + indentStep
	keyText, explicitKey := pair.key.keyToText(childIndent)
	text := keyText + ":"
	if explicitKey {
		text = "? " + keyText + "\n" + indent + ":"
	}
	valueText := valueToText(pair.value, childIndent)
	if nested, isMap := pair.value.(*yamlMap); !explicitKey && isMap && len(nested.pairs) > 0 {
		return text + "\n" + childIndent + valueText
	}
	if _, isSequence := pair.value.(flowSequence); !explicitKey && isSequence && strings.Contains(valueText, "\n") {
		return text + "\n" + childIndent + valueText
	}
	return text + " " + valueText
}

func (this nameKey) keyToText(childIndent string) (string, bool) {
	text := StringToYaml(string(this), childIndent, true)
	return text, this == "" || StringToUTF16Length(text) > maxImplicitKeyLength
}

func (this statusKey) keyToText(string) (string, bool) {
	return strconv.Itoa(int(this)), this == 0
}

// indent is the indentation of the value's own children.
func valueToText(value yamlValue, indent string) string {
	switch value := value.(type) {
	case *yamlMap:
		return mapToText(value, indent)
	case flowSequence:
		return flowSequenceToText(value, indent)
	case scalar:
		return StringToYaml(string(value), indent, false)
	case trueValue:
		return "true"
	}
	return "~"
}

func flowSequenceToText(members flowSequence, indent string) string {
	if len(members) == 0 {
		return "[]"
	}
	itemIndent := indent + indentStep + indentStep
	lines := make([]string, 0, len(members))
	for _, member := range members {
		lines = append(lines, stringToDoubleQuoted(member, itemIndent, false))
	}
	if !strings.Contains(strings.Join(lines, ""), "\n") {
		return "[" + strings.Join(lines, ", ") + "]"
	}
	var text strings.Builder
	text.WriteString("[")
	for index, line := range lines {
		if index > 0 {
			text.WriteString(",")
		}
		text.WriteString("\n" + indentStep + indent + line)
	}
	return text.String() + "\n" + indent + "]"
}
