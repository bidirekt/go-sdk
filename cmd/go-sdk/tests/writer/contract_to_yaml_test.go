func TestWritesEveryNodeTypeAndFlagInTheFixedOrder(t *testing.T) {
	equalYaml(t, writer.ContractToYaml(fullContract()), fullYaml)
}

func TestWritesTheSameTextForTheSameModel(t *testing.T) {
	equalYaml(t, writer.ContractToYaml(fullContract()), writer.ContractToYaml(fullContract()))
}

func TestWritesTheSameTextWhenResourcesAndSchemasArriveInAnotherOrder(t *testing.T) {
	contract := fullContract()
	for index := range contract.Provides {
		slices.Reverse(contract.Provides[index].Responses)
	}
	slices.Reverse(contract.Provides)
	slices.Reverse(contract.Consumes)
	slices.Reverse(contract.Schemas)

	equalYaml(t, writer.ContractToYaml(contract), fullYaml)
}

