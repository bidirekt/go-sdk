package install_test

import (
	"os"
	"os/exec"
	"path/filepath"
	"reflect"
	"strings"
	"testing"
)

const pets = `package petstore

import (
	"net/http"

	"github.com/bidirekt/go-sdk"
)

type Pet struct {
	Name string ` + "`json:\"name\" bidirekt:\"field\"`" + `
}

var _ = bidirekt.Provides(http.MethodGet, "/pets/*",
	bidirekt.Response(http.StatusOK, Pet{}),
	bidirekt.Response(http.StatusNotFound, nil),
)
`

const page = `package petstore

import (
	"io"

	"golang.org/x/net/html"
)

func Page(reader io.Reader) (*html.Node, error) {
	return html.Parse(reader)
}
`

const oldNet = "golang.org/x/net v0.38.0"

const expectedYaml = `# Generated by github.com/bidirekt/go-sdk. Do not edit.
provides:
  rest:
    /pets/*:
      get:
        responses:
          200: Pet
          404: ~
schemas:
  Pet:
    type: object
    properties:
      name:
        type: string
`

func run(t *testing.T, dir string, args ...string) string {
	t.Helper()
	command := exec.Command("go", args...)
	command.Dir = dir
	command.Env = append(os.Environ(), "GOWORK=off", "GONOPROXY=github.com/bidirekt/go-sdk", "GOVCS=github.com/bidirekt/go-sdk:off")
	output, err := command.CombinedOutput()
	if err != nil {
		t.Fatalf("go %v: got error %v, want none\n%s", args, err, output)
	}
	return string(output)
}

func write(t *testing.T, dir, name, content string) {
	t.Helper()
	if err := os.WriteFile(filepath.Join(dir, name), []byte(content), 0o644); err != nil {
		t.Fatalf("got error %v, want none", err)
	}
}

// The commands are the lines of the first sh block below "## Installation" in the README.
func readmeToInstallCommands(t *testing.T, readme string) [][]string {
	t.Helper()
	_, section, found := strings.Cut(readme, "\n## Installation\n")
	if !found {
		t.Fatalf("the README has an Installation section: got false, want true")
	}
	_, block, found := strings.Cut(section, "```sh\n")
	if !found {
		t.Fatalf("the Installation section has a sh block: got false, want true")
	}
	block, _, _ = strings.Cut(block, "```")
	var commands [][]string
	for _, line := range strings.Split(strings.TrimSpace(block), "\n") {
		fields := strings.Fields(line)
		if len(fields) < 2 || fields[0] != "go" {
			t.Fatalf("an install command: got %q, want a go command", line)
		}
		commands = append(commands, fields[1:])
	}
	return commands
}

func TestInstallsTheGeneratorWithTheReadmeCommandsInAnAppWithAnOlderXNetAndRunsIt(t *testing.T) {
	checkout, err := filepath.Abs(filepath.Join("..", "..", "..", ".."))
	if err != nil {
		t.Fatalf("got error %v, want none", err)
	}
	readme, err := os.ReadFile(filepath.Join(checkout, "README.md"))
	if err != nil {
		t.Fatalf("got error %v, want none", err)
	}
	commands := readmeToInstallCommands(t, string(readme))
	dir := t.TempDir()
	write(t, dir, "go.mod", "module example.com/petstore\n\ngo 1.26.0\n\nreplace github.com/bidirekt/go-sdk => "+checkout+"\n\nreplace github.com/bidirekt/go-sdk/cmd/go-sdk => "+filepath.Join(checkout, "cmd", "go-sdk")+"\n")
	write(t, dir, "page.go", page)
	run(t, dir, "get", strings.ReplaceAll(oldNet, " ", "@"))
	run(t, dir, "build", "./...")
	write(t, dir, "pets.go", pets)

	for _, command := range commands {
		run(t, dir, command...)
	}
	run(t, dir, "build", "./...")
	run(t, dir, "tool", "go-sdk", "generate")

	if net := strings.TrimSpace(run(t, dir, "list", "-m", "golang.org/x/net")); net == oldNet {
		t.Errorf("golang.org/x/net: got %q, want the version golang.org/x/tools needs", net)
	}
	generated, err := os.ReadFile(filepath.Join(dir, "contracts", "generated.yaml"))
	if err != nil {
		t.Fatalf("got error %v, want none", err)
	}
	equal(t, "output", string(generated), expectedYaml)
}

func equal(t *testing.T, label string, got, want any) {
	t.Helper()
	if reflect.DeepEqual(got, want) {
		return
	}
	if gotText, isText := got.(string); isText {
		t.Errorf("%s:\ngot:\n%s\nwant:\n%s", label, gotText, want)
		return
	}
	t.Errorf("%s:\ngot:  %#v\nwant: %#v", label, got, want)
}
